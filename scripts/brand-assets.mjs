/**
 * Builds brand assets from the Excel Tutors Academy logo (JPEG on a black background):
 * the black surround is flood-filled to transparent, then full logo, square marks,
 * favicon / apple-touch / PWA icons and the PDF logo are written.
 * Usage: node scripts/brand-assets.mjs assets-source/excel-logo-original.jpeg
 */
import sharp from "sharp";
import fs from "node:fs";
import path from "node:path";

const src = process.argv[2];
if (!src) throw new Error("Pass the source logo path");
const out = path.resolve("public/brand");
fs.mkdirSync(out, { recursive: true });

const { data, info } = await sharp(src).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
const { width: W, height: H } = info;
const isBg = (i) => Math.max(data[i], data[i + 1], data[i + 2]) < 38;
const seen = new Uint8Array(W * H);
const q = new Int32Array(W * H);
let head = 0, tail = 0;
const push = (x, y) => { const k = y * W + x; if (seen[k] || !isBg(k * 4)) return; seen[k] = 1; q[tail++] = k; };
for (let x = 0; x < W; x++) { push(x, 0); push(x, H - 1); }
for (let y = 0; y < H; y++) { push(0, y); push(W - 1, y); }
while (head < tail) {
  const k = q[head++]; const x = k % W, y = (k / W) | 0;
  if (x > 0) push(x - 1, y); if (x < W - 1) push(x + 1, y); if (y > 0) push(x, y - 1); if (y < H - 1) push(x, y + 1);
}
for (let k = 0; k < W * H; k++) if (seen[k]) data[k * 4 + 3] = 0;

const trimmed = await sharp(data, { raw: { width: W, height: H, channels: 4 } }).png().trim({ threshold: 1 }).png({ compressionLevel: 9 }).toBuffer();
const meta = await sharp(trimmed).metadata();
await sharp(trimmed).resize({ width: 1000 }).png({ compressionLevel: 9 }).toFile(path.join(out, "logo-full.png"));
await sharp(trimmed).resize({ width: 480 }).png({ compressionLevel: 9 }).toFile(path.join(out, "logo-full-480.png"));
await sharp(trimmed).resize({ width: 480 }).webp({ quality: 90 }).toFile(path.join(out, "logo-full-480.webp"));

const square = async (size, pad = 0.04, bg = { r: 0, g: 0, b: 0, alpha: 0 }) => {
  const inner = Math.round(size * (1 - 2 * pad));
  const r = await sharp(trimmed).resize({ width: inner, height: inner, fit: "contain", background: { r: 0, g: 0, b: 0, alpha: 0 } }).png().toBuffer();
  return sharp({ create: { width: size, height: size, channels: 4, background: bg } }).composite([{ input: r, gravity: "center" }]).png({ compressionLevel: 9 });
};
for (const s of [16, 32, 48, 64, 128, 192, 256, 512]) await (await square(s, s <= 32 ? 0.02 : 0.04)).toFile(path.join(out, `logo-mark-${s}.png`));
const white = { r: 255, g: 255, b: 255, alpha: 1 };
await (await square(180, 0.1, white)).toFile(path.resolve("src/app/apple-icon.png"));
await (await square(512, 0.16, white)).toFile(path.join(out, "maskable-512.png"));
await (await square(192, 0.16, white)).toFile(path.join(out, "maskable-192.png"));
await (await square(64, 0.02)).toFile(path.resolve("src/app/icon.png"));

const sizes = [16, 32, 48];
const pngs = await Promise.all(sizes.map(async (s) => (await square(s, 0.02)).toBuffer()));
const header = Buffer.alloc(6 + 16 * sizes.length);
header.writeUInt16LE(0, 0); header.writeUInt16LE(1, 2); header.writeUInt16LE(sizes.length, 4);
let offset = header.length;
sizes.forEach((s, i) => {
  const e = 6 + i * 16;
  header.writeUInt8(s, e); header.writeUInt8(s, e + 1); header.writeUInt8(0, e + 2); header.writeUInt8(0, e + 3);
  header.writeUInt16LE(1, e + 4); header.writeUInt16LE(32, e + 6);
  header.writeUInt32LE(pngs[i].length, e + 8); header.writeUInt32LE(offset, e + 12);
  offset += pngs[i].length;
});
fs.writeFileSync(path.resolve("src/app/favicon.ico"), Buffer.concat([header, ...pngs]));

const pdfLogo = await sharp(trimmed).resize({ width: 256 }).png({ compressionLevel: 9 }).toBuffer();
fs.writeFileSync(
  path.resolve("src/server/brand-logo.ts"),
  `// Generated by scripts/brand-assets.mjs — Excel Tutors Academy logo (transparent, 256px) for PDFs.\nexport const BRAND_LOGO_PNG_BASE64 =\n  "${pdfLogo.toString("base64")}";\n`,
);
console.log("brand assets written", { width: meta.width, height: meta.height });
